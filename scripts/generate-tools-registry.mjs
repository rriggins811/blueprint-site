#!/usr/bin/env node
// Reads the PDF filenames in the source folder and writes
// src/lib/tools-registry.generated.ts with a full TOOLS array.
// Then tools-registry.ts re-exports from there with hand-curated overrides
// (interactive componentKey, polished descriptions for built tools).

import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const SOURCE_DIR =
  "/Users/rigginsstrategicsolutions/Library/CloudStorage/OneDrive-Personal/Documents/RSS - Running The Business (chat folder)/Running the business/Running the business/Tools-Checklists Re-Write V.2 3-11-26/Edited 7-2-26";

const files = readdirSync(SOURCE_DIR)
  .filter((f) => f.endsWith(".pdf") && f.startsWith("Tool_"))
  .sort();

function entryFor(filename) {
  const stem = filename.replace(/\.pdf$/, "");
  // Tool_19A_Premium_Session_Prep → preserve "premium" for slug uniqueness
  // Tool_19B_Premium_Intake_Form
  const m = stem.match(/^Tool_(\d{2})([A-Z]+)_(.*)$/);
  if (!m) return null;
  const moduleNum = m[1];
  const suffix = m[2].toLowerCase();
  let titlePart = m[3].replace(/_/g, " ");
  // Fix common patterns: "7Day" → "7-Day", "3 Path" → "3-Path", "5 Pile" → "5-Pile"
  titlePart = titlePart
    .replace(/(\d+)Day/g, "$1-Day")
    .replace(/(\d+) Pile/g, "$1-Pile")
    .replace(/(\d+) Path/g, "$1-Path")
    .replace(/(\d+) Folder/g, "$1-Folder")
    .replace(/Two Bag/g, "Two-Bag")
    .replace(/By/g, "by")
    .replace(/Of/g, "of")
    .replace(/^by /, "By ")
    .replace(/Long Term/g, "Long-Term")
    .replace(/Spend Down/g, "Spend-Down")
    .replace(/Check In/g, "Check-In")
    .replace(/De Escalation/g, "De-Escalation");

  // Detect premium-only tools by name
  const isPremium = /Premium/i.test(filename);
  const slugBase = `tool-${moduleNum}${suffix}`;
  const slug = isPremium && /Premium_Session_Prep/i.test(filename)
    ? `${slugBase}-premium-session-prep`
    : isPremium && /Premium_Intake_Form/i.test(filename)
    ? `${slugBase}-premium-intake-form`
    : slugBase;

  // Module slug: 19A Premium Session Prep belongs to module-19-premium per inventory
  const moduleSlug = isPremium && moduleNum === "19" ? "module-19-premium" : `module-${moduleNum}`;

  return { slug, pdfName: stem, title: titlePart, moduleSlug };
}

const entries = files.map(entryFor).filter(Boolean);

// Deduplicate slugs (e.g. Tool_02A_5_Pile_Sorting_System and Tool_02A_Guide_5_Pile...)
const seen = new Set();
const unique = [];
for (const e of entries) {
  let slug = e.slug;
  let n = 1;
  while (seen.has(slug)) {
    n++;
    slug = `${e.slug}-${n}`;
  }
  seen.add(slug);
  unique.push({ ...e, slug });
}

const banner = `// AUTO-GENERATED by scripts/generate-tools-registry.mjs.
// Do not edit by hand. Run \`node scripts/generate-tools-registry.mjs\` to refresh.
// Hand-curated overrides (interactive componentKey, descriptions) live in tools-registry.ts.
`;

const code = `${banner}
export type ToolEntry = {
  slug: string;
  pdfName: string;
  title: string;
  moduleSlug: string;
};

export const RAW_TOOLS: ToolEntry[] = ${JSON.stringify(unique, null, 2)};
`;

const outPath = path.join(
  process.cwd(),
  "src",
  "lib",
  "tools-registry.generated.ts"
);
writeFileSync(outPath, code);
console.log(`Wrote ${unique.length} tools to ${outPath}`);
